#!/usr/bin/env python3
"""Generate the decompilation skeleton in /home/claude/avpe-decomp:

  include/avpe/classes.h   every class (RTTI hierarchy + PS2 class names),
                           parents first, methods listed with address,
                           calling convention and source file
  src/<File>.cpp           one per source file (symbols/source_map.csv), an
                           index of its functions; decompiled code goes here

Regenerating never overwrites a src file that already contains decompiled
code (any `void sub_XXXXXXXX(void)` definition): only the index header
between the AVPE-INDEX markers is refreshed. --exclude A.cpp,B.cpp leaves
those files untouched (someone is editing them).
"""
import csv, json, os, re, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cwdemangle import demangle

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = '/home/claude/avpe-decomp'
smap = list(csv.DictReader(open(os.path.join(R, 'symbols', 'source_map.csv'))))
abi = json.load(open(os.path.join(R, 'symbols', 'abi.json')))
classes = json.load(open(os.path.join(R, 'symbols', 'classes.json')))
db = {r['xbox']: r for r in csv.DictReader(open(os.path.join(R, 'symbols', 'xbox_symbols.csv')))}


def sig_of(name):
    if not name:
        return None
    try:
        d = demangle(name)
    except Exception:
        return None
    if not d:
        return None
    cls, meth, args, const = d
    s = ('%s::' % cls if cls else '') + '%s(%s)%s' % (meth, ', '.join(args), ' const' if const else '')
    return cls, s


def abi_str(a):
    v = abi.get(a)
    if not v:
        return '?'
    parts = []
    if v['regs']:
        parts.append('in: ' + ','.join(v['regs']))
    parts.append('pops %d' % v['pops'])
    if v['ret_eax']:
        parts.append('returns eax')
    return '; '.join(parts)


# ---- functions per file / per class
by_file = collections.OrderedDict()
by_class = collections.defaultdict(list)
game = [r for r in smap if r['how'] not in ('runtime', 'alias')]
for r in game:
    s = sig_of(r['name'])
    tier = db.get(r['xbox'], {}).get('tier', '')
    entry = dict(addr=r['xbox'], sig=s[1] if s else ('sub_%s' % r['xbox'][2:]), file=r['file'], how=r['how'],
                 tier=tier, abi=abi_str(r['xbox']))
    by_file.setdefault(r['file'], []).append(entry)
    if s and s[0]:
        by_class[s[0]].append(entry)

# ---- classes.h
allc = set(classes) | set(by_class)
def parent(c):
    return classes.get(c, {}).get('parent')
order, seen = [], set()
def visit(c):
    if c in seen:
        return
    p = parent(c)
    if p:
        visit(p)
    seen.add(c); order.append(c)
for c in sorted(allc):
    visit(c)

lines = ['/* AvP: Extinction decompilation - forward declarations of every class.',
         ' * Generated by avpe/tools/gen_decomp.py (Xbox RTTI + PS2 symbol table).',
         ' * Definitions are written by hand as classes are decompiled; see',
         ' * class_index.h for what is known about each. */',
         '#pragma once', '#include "avpe/guest.h"', '#include "avpe/types.h"', '', 'namespace avpe {', '']
for c in order:
    if '<' in c or '::' in c:
        continue          # templates and nested types: declared where decompiled
    lines.append('struct %s;' % c)
lines.append('')
lines.append('} // namespace avpe')
open(os.path.join(OUT, 'include', 'avpe', 'classes.h'), 'w').write('\n'.join(lines) + '\n')

# class_index.h: what is known about every class, as comments only. The real
# definitions are written by hand as classes are decompiled (include/avpe/*.h).
lines = ['/* AvP: Extinction - class index (generated, comments only; not included).',
         ' * Per class: parent, vtable, files its code lives in, and every method with',
         ' * address and calling convention. */', '']
for c in order:
    if '<' in c or '::' in c:
        continue
    e = classes.get(c)
    p = parent(c)
    hdr = '/* %s%s' % (c, ' : %s' % p if p else '')
    meta = []
    if e:
        vts = ', '.join('0x%08X (%d slots)' % (int(v['va'], 16), len(v['slots'])) for v in e['vtables'])
        meta.append('RTTI vtable %s' % vts)
    files = collections.Counter(x['file'] for x in by_class.get(c, []))
    if files:
        meta.append('code in ' + ', '.join(f for f, _ in files.most_common(3)))
    if meta:
        lines.append('// ' + '; '.join(meta))
    lines.append(hdr)
    for m in sorted(by_class.get(c, []), key=lambda x: x['addr']):
        lines.append(' *   %s  %s  [%s]' % (m['addr'], m['sig'].split('::', 1)[-1], m['abi']))
    lines.append(' */')
    lines.append('')
open(os.path.join(OUT, 'include', 'avpe', 'class_index.h'), 'w').write('\n'.join(lines) + '\n')

# ---- src/<File>.cpp
DEF_RE = re.compile(r'^void sub_[0-9A-Fa-f]{8}\(void\)', re.M)
BEGIN, END = '/* AVPE-INDEX BEGIN', 'AVPE-INDEX END */'
known_files = {r['file'] for r in smap if r['how'] in ('local', 'class', 'class-substr', 'filled', 'sinit')}
written = kept = 0
EXCLUDE = set(sys.argv[sys.argv.index('--exclude') + 1].split(',')) if '--exclude' in sys.argv else set()
for f, fns in by_file.items():
    if f.replace('/', '_') in EXCLUDE:                  # being edited by someone: left alone
        continue
    path = os.path.join(OUT, 'src', f.replace('/', '_'))
    hows = collections.Counter(x['how'] for x in fns)
    named = 'Zono\'s file name (PS2 symbol table)' if f in known_files else 'name inferred from its main class'
    idx = [BEGIN,
           ' * %s - AvP: Extinction decompilation' % f,
           ' * File name: %s. Placement evidence: %s' % (named, ', '.join('%s %d' % kv for kv in hows.most_common())),
           ' * %d functions. Status: [lifted] runs the translated original; [decomp] has a' % len(fns),
           ' * C++ body below; [verified] that body matched the original (verified.json).',
           ' *']
    src_now = open(path).read() if os.path.exists(path) else ''
    vj_path = os.path.join(OUT, 'verified.json')
    vj = json.load(open(vj_path)) if os.path.exists(vj_path) else {}
    for x in fns:
        st = 'lifted'
        if re.search(r'^void sub_%s\(void\)' % x['addr'][2:], src_now, re.M):
            st = 'verified' if vj.get(x['addr']) else 'decomp'
        idx.append(' *   %s  %-56s %-9s %s' % (x['addr'], x['sig'][:56], '[' + st + ']', '[' + x['abi'] + ']'))
    idx.append(' * ' + END)
    index = '\n'.join(idx)
    if os.path.exists(path):
        src = open(path).read()
        if DEF_RE.search(src) and BEGIN in src and END in src:
            a, b = src.index(BEGIN), src.index(END) + len(END)
            open(path, 'w').write(src[:a] + index + src[b:])
            kept += 1
            continue
    body = index + '\n#include "avpe/guest.h"\n#include "avpe/classes.h"\nusing namespace avpe;\n'
    open(path, 'w').write(body)
    written += 1
print('classes.h: %d classes (%d with RTTI)' % (len(order), len(classes)))
print('src: %d files written, %d with decompiled code kept' % (written, kept))
