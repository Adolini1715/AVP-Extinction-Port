#!/usr/bin/env python3
"""abi_pops_gen.py: recomp/abi_pops.inc, every function's callee-popped bytes (symbols/abi.json),
sorted by address, for the bridge's stub mode (a probe that skips the calls the function makes
needs to pop what the callee would have). Bit 31 of the second word marks a function that
returns a value in st(0): at some ret, the last x87 instruction on the way leaves a value
pushed (a load or an arithmetic op that does not pop), so a stub of it pushes one too."""
import json, os, capstone
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
a = json.load(open(R + '/symbols/abi.json'))
info = json.load(open(R + '/xbe_info.json'))
xbe = open(R + '/disc/default.xbe', 'rb').read()
md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)


def rd(va, n):
    for s in info['sections']:
        if s['va'] <= va < s['va'] + s['rsize']:
            o = s['raw'] + va - s['va']
            return xbe[o:o + min(n, s['va'] + s['rsize'] - va)]
    return b''


PUSHES = ('fld', 'fild', 'fld1', 'fldz', 'fldpi', 'fldl2e', 'fldl2t', 'fldlg2', 'fldln2')
NEUTRAL = ('fnstsw', 'fstsw', 'fnstcw', 'fstcw', 'fldcw', 'fwait', 'wait', 'fnclex', 'fclex')


def ret_st0(va, end):
    ins = list(md.disasm(rd(va, end - va), va))
    for i, x in enumerate(ins):
        if x.mnemonic != 'ret':
            continue
        for y in reversed(ins[max(0, i - 12):i]):
            m = y.mnemonic
            if m in ('call', 'jmp') or m.startswith('j') and m != 'jmp' and False:
                break
            if m in ('call',):
                break
            if m.startswith('f') and m not in NEUTRAL:
                if m in PUSHES or (not m.endswith('p') and m not in ('fstp', 'fistp', 'fcompp', 'fucompp', 'fst', 'fist', 'fcom', 'fucom', 'ftst', 'fxch', 'ffree')):
                    return True
                break
    return False


vas = sorted(int(k, 16) for k in a)
rows = []
n = 0
for j, va in enumerate(vas):
    end = vas[j + 1] if j + 1 < len(vas) else va + 0x400
    p = a['0x%08X' % va].get('pops') or 0
    f = ret_st0(va, min(end, va + 0x4000))
    n += f
    rows.append((va, p | (0x80000000 if f else 0)))
with open(R + '/recomp/abi_pops.inc', 'w') as o:
    o.write('/* generated by tools/abi_pops_gen.py from symbols/abi.json (bit 31: returns in st(0)) */\n')
    o.write('static const uint32_t s_abi_pops[][2] = {\n')
    for va, p in rows:
        o.write('    {0x%08Xu, 0x%08Xu},\n' % (va, p))
    o.write('};\n')
print(len(rows), 'functions,', n, 'return in st(0)')
