#!/usr/bin/env python3
"""noreturn_gen.py: recomp/noreturn.inc from recomp/noreturn.json (calls that never return,
spin points), for the bridge: a probe of a function that reaches one ends its capture there."""
import json, os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
d = json.load(open(R + '/recomp/noreturn.json'))
with open(R + '/recomp/noreturn.inc', 'w') as o:
    o.write('/* generated by tools/noreturn_gen.py from recomp/noreturn.json */\n')
    for k in ('callees', 'points'):
        vals = sorted(int(x, 16) for x in d[k])
        o.write('static const uint32_t s_noret_%s[] = { %s };\n' % (k, ', '.join('0x%08Xu' % v for v in vals)))
print('ok')
